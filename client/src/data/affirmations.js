/* ── Pick today's affirmation deterministically by date ── */
export function getDailyAffirmation(category, dateOverride) {
  const d = dateOverride || new Date();
  const dayOfYear = Math.floor((d - new Date(d.getFullYear(), 0, 0)) / 86400000);
  const list = AFFIRMATIONS[category] || AFFIRMATIONS.peace;
  return list[dayOfYear % list.length];
}

/* ── Calculate top categories from survey answers ── */
export function calculateProfile(answers) {
  const scores = {};
  Object.values(answers).forEach((weight) => {
    Object.entries(weight).forEach(([cat, pts]) => {
      scores[cat] = (scores[cat] || 0) + pts;
    });
  });
  // Sort descending
  return Object.entries(scores)
    .sort((a, b) => b[1] - a[1])
    .map(([cat]) => cat);  // return ranked category keys
}
